def get_treatment_extended(disease_id):
    if disease_id in TREATMENT_EXTENDED:
        return TREATMENT_EXTENDED[disease_id]
    info = DISEASE_DETAILS.get(disease_id)
    if not info:
        return None
    return _generic_extended(disease_id, info)


